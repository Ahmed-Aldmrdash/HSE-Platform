// يدويًا (arabic-reshaper) ثم تعكس ترتيب الحروف يدويًا (bidi-js) قبل
// تمريرها لـ PDFKit — على افتراض أن PDFKit لا يفهم العربية إطلاقًا.
// تبيّن بالاختبار الفعلي (توليد PDF حقيقي بأرقام إذن حقيقية، ثم فتحه
// بمحرك عرض مستقل تمامًا عن أي أداة نستخدمها للتحقق) أن الافتراض كان
// خاطئًا: PDFKit (عبر fontkit) يقوم فعليًا بتشكيل الحروف العربية
// وترتيبها بصريًا بشكل صحيح تلقائيًا — طالما الخط يدعم ذلك عربيًا
// (خط Amiri المستخدم هنا يدعمه، خط Cairo الذي تستخدمه الواجهة لا
// يدعمه، ولهذا لا يزال PDF يستخدم Amiri بدل Cairo). إعادة التشكيل
// والعكس اليدويين كانا "يصلحان" مشكلة غير موجودة أصلاً، وبفعلهما كانا
// يكسران التباعد بين الكلمات وترتيبها — وهذا بالضبط ما اشتكى منه
// المستخدم ("كلام مش مفهوم").
//
// الحل النهائي أبسط بكثير:
//   • نص عربي بحت (بما فيه أرقام/علامات ترقيم مدمجة) → يُمرَّر خام
//     بدون أي معالجة؛ PDFKit يتكفّل بالتشكيل والترتيب.
//   • نص إنجليزي/لاتيني بحت → يُمرَّر خام أيضًا (لا داعي لأي شيء).
//   • نص "مُختلَط" فعليًا (عربي + كلمات إنجليزية حقيقية بأحرف لاتينية،
//     مثال: "معتمد — APPROVED") → الحالة الوحيدة التي تحتاج تدخّلًا:
//     نعكس *ترتيب الكلمات* فقط (مقسّمة على المسافات) دون لمس ترتيب
//     الحروف *داخل* كل كلمة — لأن لمس ترتيب الحروف الداخلي هو تحديدًا
//     ما يُفسد تشكيل PDFKit التلقائي.
'use strict';

const ARABIC_LETTER_RE = /[؀-ۿݐ-ݿ]/;
const LATIN_LETTER_RE = /[A-Za-z]/;

/**
 * يجهّز نصًا لعرضه بشكل صحيح داخل PDFKit (خط Amiri).
 * @param {string} text
 * @returns {string}
 */
function prepareBidiText(text) {
  if (!text && text !== 0) return '';
  const str = String(text);
  const hasArabic = ARABIC_LETTER_RE.test(str);
  const hasLatin = LATIN_LETTER_RE.test(str);
  if (!hasArabic || !hasLatin) {
    // اتجاه واحد فقط (عربي بحت، أو لاتيني/أرقام بحتة) — PDFKit يعرضه
    // صحيحًا تمامًا من غير أي تعديل.
    return str;
  }
  // مُختلَط فعليًا: اعكس ترتيب الكلمات فقط (المسافات تبقى كما هي كفواصل)،
  // مع الحفاظ التام على ترتيب الحروف داخل كل كلمة.
  const tokens = str.split(/(\s+)/);
  return tokens.reverse().join('');
}

module.exports = { prepareBidiText };
